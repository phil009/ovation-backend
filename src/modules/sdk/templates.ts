export const CLIENT_TEMPLATE = String.raw`import createClient, { type Middleware } from 'openapi-fetch';
import type { paths } from './schema';

export interface OvationClientOptions {
  /** Server origin, e.g. https://api.example.com (no /api: the paths already include it). */
  baseUrl: string;
  /** Called before every request to get the current access token. */
  getAccessToken: () => string | null | undefined;
}

export function createOvationClient(options: OvationClientOptions) {
  const client = createClient<paths>({ baseUrl: options.baseUrl });

  const auth: Middleware = {
    onRequest({ request }) {
      const token = options.getAccessToken();
      if (token) request.headers.set('Authorization', 'Bearer ' + token);
      return request;
    },
  };
  client.use(auth);

  return client;
}

export type OvationClient = ReturnType<typeof createOvationClient>;
`;

