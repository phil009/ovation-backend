import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { IsBoolean, IsEnum, IsOptional, IsString, IsUUID, Matches, MaxLength, MinLength } from 'class-validator';
import { DonationStatus, PaymentMode } from '../../../generated/prisma/enums.js';
import { KOBO_POSITIVE } from '../../../common/money.js';

export class CreateDonationDto {
  @ApiProperty({ format: 'uuid', description: 'Generated by the client (crypto.randomUUID()) so retries are safe' })
  @IsUUID('all') id: string;

  @ApiProperty({ format: 'uuid' })
  @IsUUID('all') eventId: string;

  @ApiPropertyOptional({ type: String, format: 'uuid', nullable: true, description: 'Leave out (or null) for a general donation to all awardees' })
  @IsOptional() @IsUUID('all') awardeeId?: string | null;

  @ApiProperty({ example: 'Mrs Ngozi Okafor' })
  @IsString() @MinLength(1) @MaxLength(200) donorName: string;

  @ApiProperty({ description: 'Kobo as a digit string', example: '5000000', pattern: KOBO_POSITIVE.source })
  @Matches(KOBO_POSITIVE, { message: 'amountKobo must be a positive digit string of kobo' }) amountKobo: string;

  @ApiProperty({ enum: PaymentMode, enumName: 'PaymentMode' })
  @IsEnum(PaymentMode) paymentMode: PaymentMode;

  @ApiPropertyOptional({ enum: DonationStatus, enumName: 'DonationStatus', description: 'Defaults to PLEDGED when paymentMode is PLEDGE, otherwise RECEIVED' })
  @IsOptional() @IsEnum(DonationStatus) status?: DonationStatus;

  @ApiPropertyOptional({ description: 'Flag a hard-to-read or doubtful entry' })
  @IsOptional() @IsBoolean() needsReview?: boolean;

  @ApiPropertyOptional()
  @IsOptional() @IsString() @MaxLength(500) note?: string;
}
